const orderMap = new Map<string, number>(
  ANIME_ARCHIVE_ORDER.map((id, index) => [id, index])
);

/**
 * Sorts an array of products according to the curated Anime Archive order.
 */
export function sortAnimeArchive<T extends { id: string }>(products: T[]): T[] {
  return [...products].sort((a, b) => {
    const idxA = orderMap.get(a.id) ?? 9999;
    const idxB = orderMap.get(b.id) ?? 9999;
    return idxA - idxB;
  });
}
